// Простой вариант
void numerate(Node* node, int& counter, int reserve = 10)
{
    if (!node) return;
    
    // =====================================================
    // 1. Сначала выдаём номера всем листьям текущего уровня
    // =====================================================

    for (Node* child : node->next)
    {
        if (child->is_leaf())
        {
            child->code = counter++;
        }
    }

    // =====================================================
    // 2. Потом обрабатываем ветки
    // =====================================================

    for (Node* child : node->next)
    {
        if (!child->is_leaf())
        {
            // резервируем десяток
            counter = ((counter - 1) / reserve + 1) * reserve;

            // даём код сборке
            child->code = counter++;

            // уходим глубже
            numerate(child, counter, reserve);
        }
    }
}

// =====================================================
// 3) PRINT
// =====================================================

void print(Node* current)
{
    for (Node* child : current->next)
    {
        std::cout << child->name << " -> " << child->code << "\n";

        if (!child->is_leaf())
        {
            print(child);
        }
    }
}

