/*
========================================================
TIME COMPLEXITY:
O(N) — каждый узел посещается ограниченное число раз (в сумме 1-2 прохода)

SPACE COMPLEXITY:
O(H) — стек обхода (H = высота дерева)
========================================================
*/

class Node
{
public:
    std::string name;
    int code = -1;

    Node* prev = nullptr;
    std::vector<Node*> next;

public:
    Node(const std::string& name)
    {
        this->name = name;
    }

    void add(Node* child)
    {
        child->prev = this;
        next.push_back(child);
    }

    bool is_leaf() const
    {
        return next.empty();
    }
};



